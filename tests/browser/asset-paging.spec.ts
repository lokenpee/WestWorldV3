import { expect, test } from '@playwright/test'

test('分页保留跨页合并选择、完整详情和未保存输入', async ({ page }) => {
  await page.goto('/?acceptance=assets')
  await page.getByRole('button', { name: '装载资产样本' }).click()
  await page.getByRole('button', { name: '进入 青石镇来信' }).click()
  await page.evaluate(async () => {
    const name = (await indexedDB.databases()).find(row => row.name?.startsWith('westworld_acceptance_assets_book_'))!.name!
    const request = indexedDB.open(name)
    const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction('locations', 'readwrite')
      tx.objectStore('locations').clear()
      for (let i = 0; i < 205; i++) tx.objectStore('locations').put({ id: `L${i}`, bookId: name.slice('westworld_acceptance_assets_book_'.length), name: `地点${String(i).padStart(3, '0')}`, description: '完整描述'.repeat(300), revision: 1, createdBy: 'manual', manualSourceNote: '分页测试' })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    }); db.close()
  })
  await page.reload()
  await page.getByRole('button', { name: '进入 青石镇来信' }).click()
  await page.getByRole('button', { name: /^地点 205$/ }).click()
  await expect(page.locator('.asset-list > li')).toHaveCount(100)
  await page.getByRole('button', { name: '编辑 地点000', exact: true }).click()
  await expect(page.getByLabel('地点描述', { exact: true })).toHaveValue('完整描述'.repeat(300))
  await page.getByLabel('地点描述', { exact: true }).fill('还没保存的编辑')
  await page.getByLabel('搜索资产', { exact: true }).fill('地点204')
  await expect(page.locator('.asset-list > li')).toHaveCount(1)
  await expect(page.getByLabel('地点描述', { exact: true })).toHaveValue('还没保存的编辑')
  await page.getByRole('button', { name: '编辑 地点204', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('button', { name: '放弃并继续', exact: true }).click()
  await page.getByLabel('搜索资产', { exact: true }).fill('')
  await page.getByRole('button', { name: '手动合并', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择合并 地点000 L0', exact: true }).check()
  await page.getByRole('button', { name: '下一页资产', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择合并 地点100 L100', exact: true }).check()
  await expect(page.getByText('已选 2 项（含隐藏 1 项）', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /清除失效选择/ })).toHaveCount(0)
  await page.getByRole('button', { name: '下一页资产', exact: true }).click()
  await expect(page.locator('.asset-list > li')).toHaveCount(5)
  await page.getByRole('button', { name: '上一页资产', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '选择合并 地点100 L100', exact: true })).toBeChecked()
})
