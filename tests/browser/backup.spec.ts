import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function samples(page: Page) {
  await page.goto('/?acceptance=backup')
  await page.getByRole('button', { name: '装载备份样本', exact: true }).click()
  await page.getByRole('button', { name: '进入 青石镇来信', exact: true }).click()
}
async function download(page: Page) {
  await page.getByRole('button', { name: '导出 青石镇来信', exact: true }).click()
  const result = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载备份', exact: true }).click()
  const file = await result
  expect(file.suggestedFilename()).toMatch(/\.wwv2$/)
  await expect(page.getByRole('status').filter({ hasText: '已请求下载' })).toBeVisible()
  return readFile((await file.path())!)
}
test('真实下载、预检取消与副本恢复，刷新后保留原文与人物关联', async ({ page }, testInfo) => {
  await samples(page)
  const bytes = await download(page)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('选择备份文件（.wwv2）', { exact: true }).setInputFiles({ name: '样本.wwv2', mimeType: 'application/zip', buffer: bytes })
  await expect(page.getByRole('region', { name: '备份预检' })).toContainText('4 章 / 块 · 人物 4 · 地点 2 · 节点 4 · 事件线 2')
  await page.getByRole('button', { name: '取消恢复', exact: true }).click()
  await expect(page.getByRole('region', { name: '备份预检' })).toHaveCount(0)
  await page.getByLabel('选择备份文件（.wwv2）', { exact: true }).setInputFiles({ name: '样本.wwv2', mimeType: 'application/zip', buffer: bytes })
  await expect(page.getByText('备份校验通过', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('backup-desktop.png') })
  await page.getByRole('button', { name: '确认恢复为新书', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已恢复：青石镇来信（导入）' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '模型与存储设置', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '资产', exact: true }).click()
  await expect(page.getByRole('heading', { name: '资产书架 3' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '青石镇来信（导入）', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^事件节点 \d/ }).click()
  await page.getByRole('button', { name: '编辑 码头收信', exact: true }).click()
  await expect(page.getByLabel('已选人物')).toContainText('沈青')
  await expect(page.getByLabel('已选人物')).toContainText('顾衡')
  await page.getByRole('button', { name: '查看所选章节原文', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('船夫沈青在青石码头收到顾衡的来信。')
  await page.getByRole('button', { name: '关闭原文', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '青石镇来信（导入）', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '进入 青石镇来信', exact: true })).toBeVisible()
})

test('损坏备份清除旧预览并禁用确认，窄屏恢复与删除按钮可达', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await samples(page)
  const bytes = await download(page)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const fileInput = page.getByLabel('选择备份文件（.wwv2）', { exact: true })
  await fileInput.setInputFiles({ name: '正常.wwv2', mimeType: 'application/zip', buffer: bytes })
  await expect(page.getByRole('button', { name: '确认恢复为新书', exact: true })).toBeEnabled()
  await fileInput.setInputFiles({ name: '损坏.wwv2', mimeType: 'application/zip', buffer: Buffer.from('broken zip') })
  await expect(page.getByText('备份校验失败', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认恢复为新书', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '取消恢复', exact: true }).click()
  await fileInput.setInputFiles({ name: '正常.wwv2', mimeType: 'application/zip', buffer: bytes })
  await page.getByRole('region', { name: '备份预检' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('backup-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '取消恢复', exact: true }).click()
  await page.getByRole('button', { name: '资产', exact: true }).click()
  await page.getByRole('button', { name: '删除整书 青石镇来信', exact: true }).click()
  await page.getByRole('button', { name: '先导出', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveAccessibleName('导出 青石镇来信')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '进入 青石镇来信', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除整书 青石镇来信', exact: true }).click()
  await page.getByRole('button', { name: '确认删除整书', exact: true }).click()
  await expect(page.getByRole('button', { name: '进入 青石镇来信', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '山城来客', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('本书锁定时可导出，不能删除；另一标签看到删除，失败可通过恢复继续清理', async ({ page, context }) => {
  await samples(page)
  await page.getByRole('button', { name: '锁定世界资产', exact: true }).click()
  await expect(page.getByRole('button', { name: '删除整书 青石镇来信', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '导出 青石镇来信', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: '删除整书 山城来客', exact: true })).toBeEnabled()
  await download(page)
  await page.getByRole('button', { name: '释放验收锁', exact: true }).click()
  const second = await context.newPage()
  await second.goto('/?acceptance=backup')
  await second.getByRole('button', { name: '进入 青石镇来信', exact: true }).click()
  await page.getByRole('button', { name: '模拟下次删除失败', exact: true }).click()
  await page.getByRole('button', { name: '删除整书 青石镇来信', exact: true }).click()
  await page.getByRole('button', { name: '确认删除整书', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('删除待完成')
  await expect(second.getByRole('button', { name: '进入 青石镇来信', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.reload()
  await expect.poll(() => page.evaluate(async () => (await indexedDB.databases()).map(row => row.name))).not.toContain('westworld_acceptance_backup_book_stage1-book-a')
  await expect(page.getByRole('button', { name: '进入 山城来客', exact: true })).toBeVisible()
})

test('原生连接阻塞删除时显示待完成，释放后可手动重试', async ({ page }) => {
  await samples(page)
  await page.evaluate(async () => {
    const blocker = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('westworld_acceptance_backup_book_stage1-book-a'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    Object.assign(window, { backupDeletionBlocker: blocker })
  })
  await page.getByRole('button', { name: '删除整书 青石镇来信', exact: true }).click()
  await page.getByRole('button', { name: '确认删除整书', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('删除待完成')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '重试书籍恢复', exact: true })).toBeVisible()
  await page.evaluate(() => (window as unknown as { backupDeletionBlocker: IDBDatabase }).backupDeletionBlocker.close())
  await page.getByRole('button', { name: '重试书籍恢复', exact: true }).click()
  await expect.poll(() => page.evaluate(async () => (await indexedDB.databases()).map(row => row.name))).not.toContain('westworld_acceptance_backup_book_stage1-book-a')
  await expect(page.getByRole('button', { name: '进入 山城来客', exact: true })).toBeVisible()
})
