test('人物网络重新布局可主动触发，本机缓存刷新后恢复且不重排', async ({ page }) => {
  await samples(page)
  await page.getByRole('button', { name: '人物网络', exact: true }).click()
  const network = page.locator('.character-network')
  await expect(network.locator('canvas')).toBeVisible()
  await page.waitForFunction(() => Object.keys(localStorage).some(key => key.startsWith('wwv3:character-network:v1:')))
  const before = Number(await network.getAttribute('data-layout-count'))
  await page.getByRole('button', { name: '重新布局', exact: true }).click()
  await expect.poll(async () => Number(await network.getAttribute('data-layout-count'))).toBeGreaterThan(before)
  await page.reload()
  await page.getByRole('button', { name: '进入 青石镇来信' }).click()
  await page.getByRole('button', { name: '人物网络', exact: true }).click()
  await expect(page.locator('.character-network')).toHaveAttribute('data-layout-count', '0')
})
