import { expect, test, type Page } from '@playwright/test'

async function samples(page: Page) {
  await page.goto('/?acceptance=assets')
  await page.getByRole('button', { name: '装载资产样本' }).click()
  await page.getByRole('button', { name: '进入 青石镇来信' }).click()
  await expect(page.getByRole('region', { name: '资产管理' })).toBeVisible()
}
const person = (page: Page) => page.getByRole('button', { name: '编辑 沈青', exact: true }).filter({ hasText: '船夫' }).first()

async function relationDraft(page: Page) {
  await page.getByRole('button', { name: '添加关系', exact: true }).click()
  await page.getByLabel('搜索关系对象').fill('顾')
  await page.locator('.relation-candidates').getByRole('button', { name: /顾衡/ }).click()
  await page.getByLabel('正向标签 1').fill('朋友')
}

test('关系独立保存后背景草稿仍可保存，刷新保留两项结果', async ({ page }) => {
  await samples(page); await person(page).click()
  await page.getByLabel('背景', { exact: true }).fill('关系保存前的背景草稿')
  await relationDraft(page)
  await page.getByRole('button', { name: '保存关系', exact: true }).click()
  await expect(page.getByText('关系已保存。')).toBeVisible()
  await expect(page.getByText('此条目已被更新，请重新载入后保存。')).toHaveCount(0)
  await expect(page.getByLabel('背景', { exact: true })).toHaveValue('关系保存前的背景草稿')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.reload(); await page.getByRole('button', { name: '进入 青石镇来信' }).click(); await person(page).click()
  await expect(page.getByLabel('背景', { exact: true })).toHaveValue('关系保存前的背景草稿')
  await expect(page.locator('.relation-pair').filter({ hasText: '顾衡' })).toContainText('朋友')
})

test('关系弹窗放弃确认、刷新保护与导航保存共用草稿', async ({ page }) => {
  await samples(page); await person(page).click(); await relationDraft(page)
  await page.getByRole('dialog', { name: '编辑人物关系' }).getByRole('button', { name: '取消', exact: true }).click()
  const confirm = page.getByRole('alertdialog', { name: '放弃关系修改' })
  await expect(confirm).toBeVisible()
  await confirm.getByRole('button', { name: '继续编辑' }).click()
  await expect(page.getByLabel('正向标签 1')).toHaveValue('朋友')
  const unload = page.waitForEvent('dialog')
  await page.evaluate(() => { setTimeout(() => location.reload(), 0) })
  const native = await unload
  expect(native.type()).toBe('beforeunload'); await native.dismiss()
  // 通过顶层导航检查关系草稿也走保存/放弃/取消。
  await page.getByRole('dialog', { name: '编辑人物关系' }).getByRole('button', { name: '取消', exact: true }).click()
  await confirm.getByRole('button', { name: '放弃修改' }).click()
  await page.getByLabel('背景', { exact: true }).fill('导航同时保存的背景草稿')
  await relationDraft(page)
  await page.getByRole('button', { name: '设置', exact: true }).evaluate((button: HTMLButtonElement) => button.click())
  await page.getByRole('alertdialog', { name: '未保存的人物修改' }).getByRole('button', { name: '保存并继续' }).click()
  await expect(page.getByRole('heading', { name: '模型与存储设置' })).toBeVisible()
  await page.getByRole('button', { name: '资产', exact: true }).click(); await person(page).click()
  await expect(page.getByLabel('背景', { exact: true })).toHaveValue('导航同时保存的背景草稿')
  await expect(page.locator('.relation-pair').filter({ hasText: '顾衡' })).toContainText('朋友')
})

test('关系候选与网络姓名别名搜索超过50人可继续定位', async ({ page }) => {
  await samples(page)
  await page.evaluate(async () => {
    const request = indexedDB.open('westworld_acceptance_assets_book_stage1-book-a')
    const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction('characters', 'readwrite')
      for (let i = 0; i < 61; i++) tx.objectStore('characters').put({ id: `candidate-${i}`, bookId: 'stage1-book-a', name: `候选${String(i).padStart(2, '0')}`, aliases: [`分页别名${i}`], roleWeight: 'NPC', revision: 1, confidence: 1, createdBy: 'manual', manualSourceNote: '分页验收' })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    }); db.close()
  })
  await page.reload(); await page.getByRole('button', { name: '进入 青石镇来信' }).click(); await person(page).click()
  await page.getByRole('button', { name: '添加关系', exact: true }).click()
  await page.getByLabel('搜索关系对象').fill('候选')
  await expect(page.locator('.relation-candidates button')).toHaveCount(50)
  await page.getByRole('button', { name: '更多关系对象（共 61 人）' }).click()
  await page.locator('.relation-candidates').getByRole('button', { name: /候选60/ }).click()
  await page.getByRole('dialog', { name: '编辑人物关系' }).getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '人物网络', exact: true }).click()
  await page.getByLabel('搜索人物网络').fill('候选')
  await page.getByRole('button', { name: '更多网络人物（共 61 人）' }).click()
  await page.locator('.character-network-search').getByRole('button', { name: /候选60/ }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('候选60')
  await page.getByLabel('搜索人物网络').fill('分页别名0')
  await page.locator('.character-network-search').getByRole('button', { name: /候选00/ }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('候选00')
})

