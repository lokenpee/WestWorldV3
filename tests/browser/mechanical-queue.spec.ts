test('待合并队列可从Edge备份到Firefox，恢复副本执行且原书保持原样', async ({ page }) => {
  test.setTimeout(90000)
  await prepare(page)
  await page.getByRole('button', { name: '代码整理', exact: true }).click()
  await add(page, '沈青'); await add(page, '顾衡')
  await page.getByRole('button', { name: '导出 机械队列样本', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载备份', exact: true }).click()
  const bytes = await readFile((await (await downloading).path())!)
  const browser = await firefox.launch({ headless: true, channel: 'firefox' })
  try {
    const context = await browser.newContext({ baseURL: new URL(page.url()).origin }), other = await context.newPage()
    await other.goto('/')
    await other.getByRole('button', { name: '设置', exact: true }).click()
    await other.getByLabel('选择备份文件（.wwv2）', { exact: true }).setInputFiles({ name: '机械队列.wwv2', mimeType: 'application/zip', buffer: bytes })
    await expect(other.getByText('备份校验通过', { exact: true })).toBeVisible()
    await other.getByRole('button', { name: '确认恢复为新书', exact: true }).click()
    await expect(other.getByRole('status').filter({ hasText: '已恢复：机械队列样本（导入）' })).toBeVisible({ timeout: 20000 })
    await other.getByRole('button', { name: '资产', exact: true }).click()
    await other.getByRole('button', { name: '一键机械合并（2组）', exact: true }).click()
    await expect(other.getByRole('region', { name: '世界资产整理', exact: true })).toContainText('成功 2 组，失败 0 组，待处理 0 组', { timeout: 20000 })
    await expect(other.getByRole('button', { name: /^人物 4$/ })).toBeVisible()
    await expect(page.getByRole('button', { name: /^人物 6$/ })).toBeVisible()
    await other.reload()
    await expect(other.getByRole('region', { name: '待合并队列', exact: true })).toContainText('已合并 2 组')
  } finally { await browser.close() }
})

