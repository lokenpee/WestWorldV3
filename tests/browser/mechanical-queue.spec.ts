import { expect, firefox, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function prepare(page: Page, sameNames = false) {
  await page.goto('/')
  await page.getByLabel('小说TXT文件').setInputFiles({ name: '机械队列样本.txt', mimeType: 'text/plain', buffer: Buffer.from('第一章 交信\n沈青在客栈遇见顾衡。陆川是药师。\n第二章 后续\n顾衡将信交给沈青。陆川是镖师。') })
  await page.getByRole('button', { name: '仅导入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '机械队列样本', exact: true })).toBeVisible()
  await page.evaluate(async sameNames => {
    const name = (await indexedDB.databases()).find(row => row.name?.startsWith('westworld_canon_'))!.name!, bookId = name.slice('westworld_canon_'.length), request = indexedDB.open(name)
    const db = await new Promise<IDBDatabase>((resolve, reject) => { request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(['characters', 'locations', 'nodes', 'extractionReceipts', 'compileProgress'], 'readwrite')
      for (const [i, name] of ['沈青', '顾衡', '陆川'].entries()) for (const number of [1, 2]) tx.objectStore('characters').put({ id: `${['A', 'B', 'C'][i]}${number}`, bookId, name: sameNames || number === 1 ? name : `${name}${['船夫', '旧档', '药师'][i]}`, identity: i === 2 ? number === 1 ? '药师' : '镖师' : '原文人物', chapterIndex: String(number), chapterName: `第${number}章`, sourceChapters: [String(number)], revision: 1, confidence: 1, createdBy: 'P1' })
      for (const number of [1, 2]) {
        tx.objectStore('locations').put({ id: `L${number}`, bookId, name: !sameNames && number === 2 ? '客栈（修订版）' : '客栈', description: '镇上的客栈', chapterIndex: String(number), chapterName: `第${number}章`, sourceChapters: [String(number)], revision: 1, confidence: 1, createdBy: 'P1' })
        for (const substep of ['worldAssets', 'narrativeAssets']) tx.objectStore('extractionReceipts').put({ key: `${number}:${substep}`, bookId, chapterIndex: String(number), substep, inputFingerprint: 'fixture', originIds: [], committedAt: new Date().toISOString(), runId: 'p1-fixture' })
      }
      tx.objectStore('nodes').put({ id: 'N1', bookId, name: '交信', summary: '沈青接信', chapterIndex: '1', chapterName: '第1章', actors: ['沈青', '顾衡'], actorIds: ['A1', 'B2'], quote: '', order: 0, revision: 1, confidence: 1, createdBy: 'P1' })
      tx.objectStore('compileProgress').put({ bookId, stage: 'P1', status: 'completed', totalChapters: 2, completedChapters: ['1', '2'], failedChapters: [], updatedAt: new Date().toISOString() })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    }); db.close()
  }, sameNames)
  await page.reload()
  await expect(page.getByRole('button', { name: '代码整理', exact: true })).toBeEnabled()
}

const candidate = (page: Page, name: string, kind = '人物') => page.getByRole('region', { name: '代码整理候选', exact: true }).getByRole('button', { name: new RegExp(`^${kind} · ${name}(?:、.*?)? · 2 条$`) })
async function add(page: Page, name: string, kind = '人物') {
  await candidate(page, name, kind).click()
  await page.getByLabel('合并后主名', { exact: true }).selectOption(name)
  await page.getByRole('button', { name: '加入待合并', exact: true }).click()
  await expect(page.getByText(`已确认“${name}”并加入待合并队列。可继续核对其他候选。`, { exact: true })).toBeVisible()
}

