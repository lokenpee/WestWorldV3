import { expect, test, type Page } from '@playwright/test'

async function samples(page: Page) {
  await page.goto('/?acceptance=merge')
  await page.getByRole('button', { name: '装载合并样本', exact: true }).click()
  await page.getByRole('button', { name: '进入 渡口人物资料', exact: true }).click()
}
async function selectPeople(page: Page) {
  await page.getByRole('button', { name: '手动合并', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择合并 张三 M-P001', exact: true }).check()
  await page.getByRole('checkbox', { name: '选择合并 张清 M-P002', exact: true }).check()
  await page.getByRole('button', { name: '确定合并', exact: true }).click()
  await page.getByLabel('保留条目', { exact: true }).selectOption('M-P002')
  await page.getByLabel('合并后主名', { exact: true }).selectOption('张清')
}

test('隐藏选择保留，预览明确选择主名，合并同步节点与持久记录', async ({ page }) => {
  await samples(page)
  await page.getByRole('button', { name: '手动合并', exact: true }).click()
  await expect(page.getByRole('button', { name: '确定合并', exact: true })).toBeDisabled()
  await page.getByRole('checkbox', { name: '选择合并 张三 M-P001', exact: true }).check()
  await page.getByLabel('搜索资产').fill('张清')
  await page.getByRole('checkbox', { name: '选择合并 张清 M-P002', exact: true }).check()
  await expect(page.getByText('已选 2 项（含隐藏 1 项）')).toBeVisible()
  await page.getByRole('button', { name: '确定合并', exact: true }).click()
  await expect(page.getByRole('button', { name: '确认机械合并' })).toBeDisabled()
  await page.getByLabel('保留条目', { exact: true }).selectOption('M-P002')
  await page.getByLabel('合并后主名', { exact: true }).selectOption('张清')
  await expect(page.getByRole('region', { name: '融合结果' })).toContainText('住在河边')
  await expect(page.getByRole('region', { name: '融合结果' })).toContainText('穿青衣')
  await page.getByRole('button', { name: '确认机械合并' }).click()
  await expect(page.getByRole('status').filter({ hasText: '合并完成' })).toContainText('减少 1 条')
  await expect(page.getByRole('button', { name: '编辑 张三', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '编辑 张清', exact: true })).toBeVisible()
  await expect(page.getByLabel('别名', { exact: true })).toHaveValue(/张三/)
  await page.getByRole('button', { name: /^事件节点 \d/ }).click()
  await page.getByRole('button', { name: '编辑 交付信件', exact: true }).click()
  await expect(page.getByRole('button', { name: /^移除人物 张清 / })).toHaveCount(1)
  await expect(page.getByLabel('已选人物')).toContainText('李四')
  await page.reload()
  await page.getByRole('button', { name: '进入 渡口人物资料', exact: true }).click()
  await page.getByRole('button', { name: '合并记录（1）', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('人物：3 → 2')
  await expect(page.getByRole('dialog')).toContainText('M-P001')
  await expect(page.getByRole('dialog')).toContainText('M-P002')
})

test('取消预览不写入，选择保留，退出后恢复普通列表', async ({ page }) => {
  await samples(page)
  await selectPeople(page)
  await page.getByLabel('自定义主名').fill('张清新名')
  await page.getByRole('button', { name: '取消预览' }).click()
  await expect(page.getByRole('checkbox', { name: '选择合并 张三 M-P001', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '退出合并' }).click()
  await expect(page.getByRole('button', { name: '编辑 张三', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑 张清新名', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^合并记录/ })).toHaveCount(0)
})

test('预览后另一标签修改资料，确认拒绝并可刷新预览', async ({ page, context }) => {
  await samples(page)
  await selectPeople(page)
  const other = await context.newPage()
  await other.goto('/?acceptance=merge')
  await other.getByRole('button', { name: '进入 渡口人物资料', exact: true }).click()
  await other.getByRole('button', { name: '编辑 张三', exact: true }).click()
  await other.getByLabel('背景', { exact: true }).fill('另一页面保存的新背景')
  await other.getByRole('button', { name: '保存', exact: true }).click()
  await expect(other.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  await page.getByRole('button', { name: '确认机械合并' }).click()
  await expect(page.getByRole('alert')).toContainText('刷新合并预览')
  await page.getByRole('button', { name: '刷新预览' }).click()
  await expect(page.getByRole('region', { name: '融合结果' })).toContainText('另一页面保存的新背景')
  await page.getByRole('button', { name: '确认机械合并' }).click()
  await expect(page.getByLabel('背景', { exact: true })).toHaveValue('另一页面保存的新背景')
})

test('预览中被删除的成员不会悄悄跳过，返回后可清除失效选择', async ({ page, context }) => {
  await samples(page)
  await selectPeople(page)
  const other = await context.newPage()
  await other.goto('/?acceptance=merge')
  await other.getByRole('button', { name: '进入 渡口人物资料', exact: true }).click()
  await other.getByRole('button', { name: '编辑 张三', exact: true }).click()
  await other.getByRole('button', { name: '删除条目', exact: true }).click()
  await other.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(other.getByRole('button', { name: '编辑 张三', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '确认机械合并' }).click()
  await expect(page.getByRole('alert')).toContainText('已变化或删除')
  await page.getByRole('button', { name: '取消预览' }).click()
  await page.getByRole('button', { name: '清除失效选择（1）' }).click()
  await expect(page.getByRole('button', { name: '确定合并', exact: true })).toBeDisabled()
})

