import { expect, test } from '@playwright/test'

test('隔离演示支持固定故障、实际次数和窄屏操作', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/?acceptance=models')
  await page.getByRole('button', { name: '填入演示配置', exact: true }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '测试整理模型', exact: true }).click()
  await expect(page.getByRole('region', { name: '整理测试结果', exact: true })).toContainText('整理测试成功')
  await page.getByRole('button', { name: '首次服务失败', exact: true }).click()
  await page.getByRole('button', { name: '测试提取模型', exact: true }).click()
  await expect(page.getByRole('region', { name: '提取测试结果', exact: true })).toContainText('实际请求：2 次')
  await page.getByRole('button', { name: '限流等待', exact: true }).click()
  await page.getByRole('button', { name: '测试提取模型', exact: true }).click()
  await expect(page.getByRole('region', { name: '提取测试结果', exact: true })).toContainText(/等待 (?:[1-9]|[12]\d|30) 秒后重试/)
  await page.getByRole('button', { name: '取消提取测试', exact: true }).click()
  await expect(page.getByRole('region', { name: '提取测试结果', exact: true })).toContainText('已取消')
  await page.getByRole('button', { name: '在途等待', exact: true }).click()
  await page.getByRole('button', { name: '测试整理模型', exact: true }).click()
  await expect(page.getByRole('region', { name: '整理测试结果', exact: true })).toContainText('第 1 次请求')
  await page.getByRole('button', { name: '取消整理测试', exact: true }).click()
  await expect(page.getByRole('region', { name: '整理测试结果', exact: true })).toContainText('已取消')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('region', { name: '提取测试结果', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('models-mobile.png') })
})
