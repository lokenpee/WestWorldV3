test('滑轮以鼠标为锚点缩放，筛选恢复画布后仍能缩放且页面不滚动', async ({ page }) => {
  await prepare(page)
  const network = page.getByRole('region', { name: '事件网络', exact: true })
  const canvas = network.locator('svg')
  for (const restore of [false, true]) {
    if (restore) {
      await network.getByLabel('搜索事件网络').fill('没有这个节点')
      await expect(canvas).toHaveCount(0)
      await network.getByLabel('搜索事件网络').fill('')
    }
    await canvas.scrollIntoViewIfNeeded()
    const rect = (await canvas.boundingBox())!
    const point = { x: Math.round(rect.x + rect.width * 0.3), y: Math.round(rect.y + rect.height * 0.6) }
    const graphPoint = () => canvas.evaluate((element, point) => {
      const svg = element as SVGSVGElement
      const graph = new DOMPoint(point.x, point.y).matrixTransform(svg.getScreenCTM()!.inverse())
      return { x: graph.x, y: graph.y }
    }, point)
    const before = await graphPoint()
    const zoom = await network.getByLabel('网络缩放比例').textContent()
    const scroll = await page.evaluate(() => ({ x: scrollX, y: scrollY, panels: Array.from(document.querySelectorAll('.workspace-content, .assets-panel')).map(el => el.scrollTop) }))
    await page.mouse.move(point.x, point.y)
    await page.mouse.wheel(0, -150)
    await expect(network.getByLabel('网络缩放比例')).not.toHaveText(zoom!)
    const after = await graphPoint()
    expect(after.x).toBeCloseTo(before.x, 2)
    expect(after.y).toBeCloseTo(before.y, 2)
    expect(await page.evaluate(() => ({ x: scrollX, y: scrollY, panels: Array.from(document.querySelectorAll('.workspace-content, .assets-panel')).map(el => el.scrollTop) }))).toEqual(scroll)
  }
})

