import { expect, test, type Page } from '@playwright/test'

async function prepare(page: Page) {
  await page.goto('/')
  await page.getByLabel('小说TXT文件').setInputFiles({ name: '网络样本.txt', mimeType: 'text/plain', buffer: Buffer.from('第一章 开始\n甲乙会面。\n第二章 后续\n后续事件。') })
  await page.getByRole('button', { name: '仅导入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '网络样本', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const name = (await indexedDB.databases()).find(row => row.name?.startsWith('westworld_canon_'))!.name!
    const bookId = name.slice('westworld_canon_'.length), request = indexedDB.open(name)
    const db = await new Promise<IDBDatabase>((resolve, reject) => { request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    const nodes = ['发现线索', '共同节点', '后续事件', '独立日常'].map((name, i) => ({ id: `N${i + 1}`, bookId, name, summary: `${name}的实际经过`, actors: [], quote: '', chapterIndex: i < 2 ? '1' : '2', chapterName: i < 2 ? '第一章 开始' : '第二章 后续', order: i % 2, revision: 1, confidence: 1, createdBy: 'P1', eventLineIds: i === 0 ? ['L1'] : i === 1 ? ['L1', 'L2'] : i === 2 ? ['L2'] : [] }))
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(['nodes', 'eventLines'], 'readwrite')
      for (const row of nodes) tx.objectStore('nodes').put(row)
      for (const [i, title] of ['调查主线', '人物支线'].entries()) tx.objectStore('eventLines').put({ id: `L${i + 1}`, bookId, title, nodeIds: i ? ['N2', 'N3'] : ['N1', 'N2'], chapters: i ? ['1', '2'] : ['1'], cause: '线索出现', process: '调查经过', result: '继续调查', lineStatus: 'open', revision: 1, createdBy: 'P3', updatedAt: new Date().toISOString() })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    }); db.close()
  })
  await page.reload()
  await page.getByRole('button', { name: /^事件节点 4$/ }).click()
  await page.getByRole('button', { name: '事件网络', exact: true }).click()
}

test('网络展示共享节点和孤点，高亮、详情、搜索与列表切换保持结果', async ({ page }, testInfo) => {
  await prepare(page)
  const network = page.getByRole('region', { name: '事件网络', exact: true })
  await expect(network).toContainText('显示 4 / 4 个节点')
  await expect(network).toContainText('1 个孤立节点 · 1 个共享节点')
  await expect(network.locator('[data-network-node="N2"]')).toHaveCount(1)
  await expect(network.locator('[data-network-edge]')).toHaveCount(2)
  await network.getByRole('button', { name: /调查主线/ }).click()
  await expect(network.locator('[data-network-node="N3"]')).toHaveAttribute('opacity', '0.3')
  await network.getByRole('button', { name: '查看节点 共同节点 N2', exact: true }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('共同节点')
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await network.getByLabel('搜索事件网络').fill('独立日常')
  await expect(network).toContainText('显示 1 / 4 个节点')
  await page.getByRole('button', { name: '列表', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑 共同节点', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '事件网络', exact: true }).click()
  await expect(network.getByLabel('搜索事件网络')).toHaveValue('独立日常')
  await network.getByLabel('搜索事件网络').fill('')
  await network.getByLabel('只看孤立节点').check()
  await expect(network.locator('[data-network-node]')).toHaveCount(1)
  await network.getByLabel('只看孤立节点').uncheck()
  await network.getByRole('button', { name: '查看全图', exact: true }).click()
  await network.screenshot({ path: testInfo.outputPath('network-desktop.png') })
})

test('手机网络可缩放、按章节筛选并定位节点，布局不改资产', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await prepare(page)
  const network = page.getByRole('region', { name: '事件网络', exact: true })
  const zoom = await network.getByLabel('网络缩放比例').textContent()
  await network.getByRole('button', { name: '放大事件网络', exact: true }).click()
  await expect(network.getByLabel('网络缩放比例')).not.toHaveText(zoom!)
  await network.getByLabel('筛选网络章节').selectOption('2')
  await expect(network).toContainText('显示 2 / 4 个节点')
  await network.getByLabel('定位事件节点').selectOption('N4')
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('独立日常')
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await network.screenshot({ path: testInfo.outputPath('network-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const revisions = await page.evaluate(async () => {
    const name = (await indexedDB.databases()).find(row => row.name?.startsWith('westworld_canon_'))!.name!, request = indexedDB.open(name)
    const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result) })
    const rows = await new Promise<{ revision: number }[]>(resolve => { const request = db.transaction('nodes').objectStore('nodes').getAll(); request.onsuccess = () => resolve(request.result) }); db.close()
    return rows.map(row => row.revision)
  })
  expect(revisions).toEqual([1, 1, 1, 1])
})

test('键盘打开详情后编辑或删除节点，网络同步更新实际资产', async ({ page }) => {
  await prepare(page)
  const network = page.getByRole('region', { name: '事件网络', exact: true })
  const canvas = network.getByRole('group', { name: '事件网络画布，方向键移动，加减键缩放', exact: true })
  const before = await canvas.getAttribute('viewBox')
  await canvas.focus(); await canvas.press('ArrowRight')
  await expect(canvas).not.toHaveAttribute('viewBox', before!)
  await network.getByRole('button', { name: '查看全图', exact: true }).click()
  const shared = network.getByRole('button', { name: '查看节点 共同节点 N2', exact: true })
  await shared.focus(); await shared.press('Enter')
  await page.getByLabel('名称', { exact: true }).fill('共同节点已更新')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(network.getByRole('button', { name: '查看节点 共同节点已更新 N2', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除条目', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(network).toContainText('显示 3 / 3 个节点')
  await expect(network.locator('[data-network-node="N2"]')).toHaveCount(0)
  await expect(network).toContainText('0 个共享节点')
  await expect(network.locator('[data-network-edge]')).toHaveCount(0)
})

test('千节点网络可搜索定位末项，筛选后保持实际总数', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  await prepare(page)
  await page.evaluate(async () => {
    const name = (await indexedDB.databases()).find(row => row.name?.startsWith('westworld_canon_'))!.name!, bookId = name.slice('westworld_canon_'.length), request = indexedDB.open(name)
    const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(['nodes', 'eventLines'], 'readwrite'), nodes = tx.objectStore('nodes'), lines = tx.objectStore('eventLines')
      nodes.clear(); lines.clear()
      for (let i = 0; i < 1000; i++) nodes.put({ id: `BIG-${String(i).padStart(4, '0')}`, bookId, name: `大节点${i}`, summary: `第${i}个节点的完整概述`, actors: [], quote: '', chapterIndex: i < 500 ? '1' : '2', chapterName: i < 500 ? '第一章' : '第二章', order: i % 500, revision: 1, confidence: 1, createdBy: 'P1', eventLineIds: i === 999 ? [] : [`BIG-L${Math.floor(i / 10)}`] })
      for (let i = 0; i < 100; i++) lines.put({ id: `BIG-L${i}`, bookId, title: `大事件线${i}`, nodeIds: Array.from({ length: i === 99 ? 9 : 10 }, (_, j) => `BIG-${String(i * 10 + j).padStart(4, '0')}`), chapters: [i < 50 ? '1' : '2'], cause: '', process: '', result: '', lineStatus: 'open', revision: 1, createdBy: 'P3', updatedAt: new Date().toISOString() })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    }); db.close()
  })
  await page.reload()
  await page.getByRole('button', { name: /^事件节点 1000$/ }).click()
  await page.getByRole('button', { name: '事件网络', exact: true }).click()
  const network = page.getByRole('region', { name: '事件网络', exact: true })
  await expect(network).toContainText('显示 1000 / 1000 个节点', { timeout: 15000 })
  await network.getByLabel('搜索事件网络').fill('BIG-0999')
  await expect(network).toContainText('显示 1 / 1000 个节点')
  await expect(network.locator('[data-network-node]')).toHaveCount(1)
  await network.getByLabel('定位事件节点').selectOption('BIG-0999')
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('大节点999')
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await network.screenshot({ path: testInfo.outputPath('network-large-filtered.png') })
})
