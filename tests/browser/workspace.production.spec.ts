import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('生产包不开放验收入口、不加载样本、不请求外部服务', async ({ page }) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', async route => {
    if (new URL(route.request().url()).hostname !== '127.0.0.1') {
      external.push(route.request().url())
      await route.abort()
    } else await route.continue()
  })
  await page.goto('/?acceptance=stage1')
  await expect(page.getByRole('heading', { name: '资产书架 0' })).toBeVisible()
  await expect(page.getByRole('region', { name: '阶段1隔离验收' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '装载两本样本' })).toHaveCount(0)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('heading', { name: '模型与存储设置' })).toBeVisible()
  expect(await page.evaluate(async () => (await indexedDB.databases()).map(db => db.name))).toEqual(['westworld_settings'])
  expect(external).toEqual([])
  expect(errors).toEqual([])
  await page.goto('/?acceptance=models')
  await expect(page.getByRole('region', { name: '模型调用隔离验收', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '填入演示配置', exact: true })).toHaveCount(0)
})

test('生产构建可导入原文、维护资产并持久保存', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('小说TXT文件').setInputFiles({ name: '生产验证.txt', mimeType: 'text/plain', buffer: Buffer.from('序文保留\n第一章 生产验证\n正文完整。') })
  await expect(page.getByRole('region', { name: '分章预览' })).toContainText('2 章 / 块')
  await page.getByRole('button', { name: '仅导入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '生产验证', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '查看原文 第一章 生产验证', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('正文完整。')
  await page.getByRole('button', { name: '关闭原文' }).click()
  await page.getByRole('button', { name: '新增人物', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('生产人物')
  await page.getByLabel('来源章节', { exact: true }).selectOption('1')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑 生产人物', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑 生产人物', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新增人物', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('生产人物别名')
  await page.getByLabel('来源章节', { exact: true }).selectOption('1')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑 生产人物别名', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '手动合并', exact: true }).click()
  await page.getByRole('checkbox', { name: /^选择合并 生产人物 / }).check()
  await page.getByRole('checkbox', { name: /^选择合并 生产人物别名 / }).check()
  await page.getByRole('button', { name: '确定合并', exact: true }).click()
  await page.getByLabel('合并后主名', { exact: true }).selectOption('生产人物')
  await page.getByRole('button', { name: '确认机械合并', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '合并完成' })).toContainText('减少 1 条')
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑 生产人物别名', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '合并记录（1）', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('生产人物别名')
  await page.getByRole('button', { name: '关闭记录', exact: true }).click()
  await page.getByRole('button', { name: /^事件节点 \d/ }).click()
  await page.getByRole('button', { name: '新增事件节点', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('生产事件')
  await page.getByLabel('概述', { exact: true }).fill('人物在码头收信')
  await page.getByLabel('所属章节', { exact: true }).selectOption('1')
  await page.getByRole('checkbox', { name: /^选择人物 生产人物 / }).check()
  await page.getByLabel('补充人物称呼', { exact: true }).fill('送信人')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑 生产事件', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /^事件节点 \d/ }).click()
  await page.getByRole('button', { name: '编辑 生产事件', exact: true }).click()
  await expect(page.getByLabel('已选人物')).toContainText('生产人物')
  await expect(page.getByLabel('补充人物称呼', { exact: true })).toHaveValue('送信人')
  await page.getByRole('button', { name: '导出 生产验证', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载备份', exact: true }).click()
  const bytes = await readFile((await (await download).path())!)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('选择备份文件（.wwv2）', { exact: true }).setInputFiles({ name: '生产备份.wwv2', mimeType: 'application/zip', buffer: bytes })
  await expect(page.getByText('备份校验通过', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认恢复为新书', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已恢复：生产验证（导入）' })).toBeVisible()
  await page.getByRole('button', { name: '资产', exact: true }).click()
  await expect(page.getByRole('heading', { name: '生产验证（导入）', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除整书 生产验证（导入）', exact: true }).click()
  await page.getByRole('button', { name: '确认删除整书', exact: true }).click()
  await expect(page.getByRole('button', { name: '进入 生产验证（导入）', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '进入 生产验证', exact: true })).toBeVisible()
})
